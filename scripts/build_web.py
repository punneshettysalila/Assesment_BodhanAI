from __future__ import annotations

import json
import os
import shutil
import stat
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
WEB_ROOT = ROOT / "web"
SAMPLE_ROOT = ROOT / "bodhan-narrated-lesson" / "examples" / "offline_demo_output"
SAMPLE_LANGUAGES = ("hi", "ta", "bn")
APP_FILES = ("index.html", "styles.css", "app.js")
BUILD_MARKER = ".bodhan-web-build"


def remove_readonly(func, path, error) -> None:
    if not isinstance(error[1], PermissionError):
        raise error[1]
    os.chmod(path, os.stat(path).st_mode | stat.S_IWRITE)
    func(path)


def validate_sample_assets() -> None:
    report_path = SAMPLE_ROOT / "report.json"
    report = json.loads(report_path.read_text(encoding="utf-8"))
    if not isinstance(report.get("languages"), dict):
        raise ValueError("The offline sample report has no language results.")

    required = [
        SAMPLE_ROOT / "OFFLINE_DEMO_NOT_REAL_BODHAN.txt",
        SAMPLE_ROOT / "source" / "lesson.en.md",
    ]
    for language in SAMPLE_LANGUAGES:
        language_output = SAMPLE_ROOT / language
        if language not in report["languages"]:
            raise ValueError(f"The offline sample report has no {language} results.")
        required.extend(
            language_output / name
            for name in (f"lesson.{language}.md", f"chapters.{language}.json")
        )
        required.append(language_output / "narration")

    missing = [path for path in required if not path.exists()]
    if missing:
        paths = ", ".join(str(path) for path in missing)
        raise FileNotFoundError(f"Offline sample assets are missing: {paths}")


def build_site(destination: Path) -> Path:
    destination = destination.resolve()
    if destination == ROOT or destination in ROOT.parents:
        raise ValueError(f"Refusing to build over the repository or its parent: {destination}")
    if not WEB_ROOT.is_dir():
        raise FileNotFoundError(f"The web app is missing: {WEB_ROOT}")
    validate_sample_assets()
    if destination.exists():
        if not (destination / BUILD_MARKER).is_file():
            raise FileExistsError(
                f"Refusing to replace {destination}; it is not marked as a generated Bodhan web build."
            )
        shutil.rmtree(destination, onerror=remove_readonly)
    destination.mkdir(parents=True)
    (destination / BUILD_MARKER).write_text("Generated by scripts/build_web.py\n", encoding="utf-8")

    for name in APP_FILES:
        source = WEB_ROOT / name
        if not source.is_file():
            raise FileNotFoundError(f"Required web app file is missing: {source}")
        shutil.copy2(source, destination / name)

    sample_destination = destination / "sample-data"
    sample_destination.mkdir()
    for name in ("report.json", "OFFLINE_DEMO_NOT_REAL_BODHAN.txt"):
        shutil.copy2(SAMPLE_ROOT / name, sample_destination / name)
    source_destination = sample_destination / "source"
    source_destination.mkdir()
    shutil.copy2(SAMPLE_ROOT / "source" / "lesson.en.md", source_destination / "lesson.en.md")

    for language in SAMPLE_LANGUAGES:
        source_language = SAMPLE_ROOT / language
        if not source_language.is_dir():
            raise FileNotFoundError(f"Sample language output is missing: {source_language}")
        target_language = sample_destination / language
        target_language.mkdir()
        for name in (f"lesson.{language}.md", f"chapters.{language}.json"):
            shutil.copy2(source_language / name, target_language / name)
        shutil.copytree(source_language / "narration", target_language / "narration")
    return destination


def main() -> int:
    destination = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "dist"
    try:
        built = build_site(destination)
    except (OSError, ValueError) as error:
        print(f"Web build failed: {error}", file=sys.stderr)
        return 1
    print(f"Built the static app in {built}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
